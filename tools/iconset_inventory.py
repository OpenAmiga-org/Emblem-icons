"""iconset_inventory.py LISTING [OUT.md]          the inventory document from a guest listing
   iconset_inventory.py LISTING check NAME...      what each name is (drawer / file / icon only); NAME
                                                   bare (every match) or DIR/NAME; exit 1 if any is a drawer

LISTING: the output of `List DIR... LFORMAT "%P%N|%L"` on the OS 4.1 guest (one entry per line,
"SYS:Prefs/Presets|Dir" or "SYS:Prefs/AHI|73068"). Every entry with a .info of its own is classified:

  drawer     a directory with its own icon: the glass drawer + an emblem (never an object)
  file       a program or project with its own icon: an object of its own (group 4)
  icon only  an icon whose file is not there (e.g. Shell.info, "Edit Connection.info")

Directories without an icon keep none and get def_drawer (the general rule of 2026-11-15).
The user (2026-11-16): drawers must be handled as drawers, never drawn as programs by mistake, so
every batch is checked against this before anything is designed. Public domain.
"""
import collections
import sys


def load(path):
    entries = collections.OrderedDict()
    for line in open(path, encoding="latin-1"):
        line = line.rstrip("\n")
        if "|" not in line:
            continue
        name, size = line.rsplit("|", 1)
        entries[name] = size
    return entries


def classify(entries):
    """{directory: [(name, kind)]} for every icon, plus {directory: [drawers without an icon]}"""
    icons, bare = collections.OrderedDict(), collections.OrderedDict()
    low = {k.lower(): v for k, v in entries.items()}          # AmigaDOS names ignore case
    for full, size in entries.items():
        d, _, n = full.rpartition("/") if "/" in full else full.partition(":")
        d = d if "/" in full else d + ":"
        if n.lower().endswith(".info"):
            base = full[:-5].lower()
            kind = "drawer" if low.get(base) == "Dir" else ("file" if base in low else "icon only")
            icons.setdefault(d, []).append((n[:-5], kind))
        elif size == "Dir" and (full + ".info").lower() not in low:
            bare.setdefault(d, []).append(n)
    return icons, bare


def main():
    entries = load(sys.argv[1])
    icons, bare = classify(entries)
    if len(sys.argv) > 2 and sys.argv[2] == "check":
        bad = 0
        for n in sys.argv[3:]:                # a bare name, or DIR/NAME (e.g. SYS:Prefs/Presets)
            want_d, _, want_n = n.rpartition("/")
            hits = [(d, k) for d, lst in icons.items() for m, k in lst
                    if m.lower() == want_n.lower() and (not want_d or d.lower() == want_d.lower())]
            for d, k in hits or [("?", "not found")]:
                print(f"{n}: {k} ({d})")
                bad += k not in ("file", "icon only")
        sys.exit(1 if bad else 0)
    out = sys.argv[2] if len(sys.argv) > 2 else None
    lines = ["# Icon inventory of a stock OS 4.1 FE Update 3 install (QEMU guest)", "",
             "Generated by tools/iconset_inventory.py from a guest listing. **drawer** = the glass drawer + an",
             "emblem (never an object); **file** = a program or project, an object of its own; **icon only** =",
             "an icon without its file. Drawers without an icon keep none (def_drawer).", ""]
    for d, lst in icons.items():
        lines.append(f"## {d}")
        lines.append("")
        for kind in ("drawer", "file", "icon only"):
            names = [n for n, k in lst if k == kind]
            if names:
                lines.append(f"- **{kind}** ({len(names)}): " + ", ".join(names))
        if bare.get(d):
            lines.append(f"- drawers without an icon (def_drawer): " + ", ".join(bare[d]))
        lines.append("")
    text = "\n".join(lines)
    if out:
        open(out, "w").write(text)
        print("inventory ->", out)
    else:
        print(text)


if __name__ == "__main__":
    main()
